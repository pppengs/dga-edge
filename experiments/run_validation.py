# -*- coding: utf-8 -*-
"""experiments.run_validation

Batch validation of every diagnostic method against the public datasets.

Produces:
    experiments/results/per_sample_<dataset>.csv
    experiments/results/summary.csv
    experiments/results/REPORT.md

Host-side only (needs openpyxl to read the raw datasets).
"""

import os
import sys
from collections import Counter, OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from dga_core import DEFAULT_METHODS  # noqa: E402
from dga_service.pipeline import run_batch  # noqa: E402
from dga_service.io_utils import write_csv, results_to_rows, sentinel_report  # noqa: E402
from experiments.loaders import DATASETS  # noqa: E402

OUT = os.path.join(HERE, "results")

# Codes that mean "the method declined to answer".
UNDECIDED = ("ND", "N/A", "-")


def metrics(pairs, classes):
    """pairs: list of (truth, predicted) over samples the method decided on."""
    per_class_total = Counter(t for t, _ in pairs)
    per_class_hit = Counter(t for t, p in pairs if t == p)
    per_class_pred = Counter(p for _, p in pairs)

    recall = OrderedDict()
    precision = OrderedDict()
    f1 = OrderedDict()
    for c in classes:
        tot = per_class_total.get(c, 0)
        hit = per_class_hit.get(c, 0)
        pred = per_class_pred.get(c, 0)
        r = hit / tot if tot else 0.0
        p = hit / pred if pred else 0.0
        recall[c] = r
        precision[c] = p
        f1[c] = (2 * p * r / (p + r)) if (p + r) else 0.0
    macro_f1 = sum(f1.values()) / len(f1) if f1 else 0.0
    return recall, precision, f1, macro_f1


def evaluate(name, labelled, methods, subset="all"):
    samples = [s for s, _ in labelled]
    truth = dict((s.sample_id, t) for s, t in labelled)

    report = run_batch(samples, methods=methods)
    write_csv(os.path.join(OUT, "per_sample_{}_{}.csv".format(name, subset)),
              results_to_rows(report.results))

    classes = sorted(set(t for t in truth.values() if t))
    rows = []
    confusion = {}
    for m in methods:
        decided_pairs = []
        n_decided = 0
        n_correct = 0
        n_total = 0
        for res in report.results:
            t = truth.get(res.sample_id)
            if not t:
                continue
            n_total += 1
            code = None
            applicable = False
            for mr in res.results:
                if mr.method == m:
                    code = mr.code
                    applicable = mr.applicable
            if applicable and code not in UNDECIDED:
                n_decided += 1
                decided_pairs.append((t, code))
                if code == t:
                    n_correct += 1
        recall, precision, f1, macro_f1 = metrics(decided_pairs, classes)
        confusion[m] = Counter((t, p) for t, p in decided_pairs)
        rows.append(OrderedDict([
            ("dataset", name),
            ("subset", subset),
            ("method", m),
            ("n_total", n_total),
            ("n_decided", n_decided),
            ("decision_rate_pct", round(100.0 * n_decided / n_total, 1) if n_total else 0.0),
            ("acc_of_decided_pct", round(100.0 * n_correct / n_decided, 1) if n_decided else 0.0),
            ("acc_of_all_pct", round(100.0 * n_correct / n_total, 1) if n_total else 0.0),
            ("macro_f1", round(macro_f1, 4)),
        ] + [("recall_" + c, round(recall[c], 3)) for c in classes]))
    return rows, confusion, report, classes


def write_report(all_rows, confusions, classes, dataset_notes):
    lines = []
    lines.append("# DGA method validation report")
    lines.append("")
    lines.append("Generated by `experiments/run_validation.py`.")
    lines.append("")
    lines.append("## Metrics")
    lines.append("")
    lines.append("- `decision_rate` - share of samples the method was willing to judge.")
    lines.append("- `acc_of_decided` - accuracy counted only over decided samples.")
    lines.append("- `acc_of_all` - accuracy over every sample, undecided counted as wrong.")
    lines.append("  These two differ a lot and must be reported together; quoting only")
    lines.append("  one of them is the most common way DGA comparisons mislead.")
    lines.append("")
    lines.append("## Results")
    lines.append("")
    header = ["dataset", "subset", "method", "n", "decided", "decision%",
              "acc_decided%", "acc_all%", "macro-F1"]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "|".join(["---"] * len(header)) + "|")
    for r in all_rows:
        lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            r["dataset"], r["subset"], r["method"], r["n_total"], r["n_decided"],
            r["decision_rate_pct"], r["acc_of_decided_pct"],
            r["acc_of_all_pct"], r["macro_f1"]))
    lines.append("")
    lines.append("`faults_only` drops samples labelled Normal. Duval Triangle has no")
    lines.append("normal zone, so it is forced to misclassify every healthy unit.")
    lines.append("")
    lines.append("## Per-class recall")
    lines.append("")
    lines.append("| dataset | subset | method | " + " | ".join(classes) + " |")
    lines.append("|" + "|".join(["---"] * (3 + len(classes))) + "|")
    for r in all_rows:
        lines.append("| {} | {} | {} | {} |".format(
            r["dataset"], r["subset"], r["method"],
            " | ".join(str(r.get("recall_" + c, "")) for c in classes)))
    lines.append("")
    lines.append("## Datasets")
    lines.append("")
    for note in dataset_notes:
        lines.append("- {}".format(note))
    lines.append("")
    lines.append("## Caveats")
    lines.append("")
    lines.append("- Labels are the datasets' own published annotations, not independent")
    lines.append("  physical inspection. They are treated as ground truth for comparison only.")
    lines.append("- `中低温过热` in the Cliango dataset merges two IEC thermal tiers and is")
    lines.append("  mapped to T1, which is a lossy mapping.")
    lines.append("- The IEC three-ratio coded variant returns ND for code triples that the")
    lines.append("  literature documents inconsistently (see dga_core/tables.py).")
    return "\n".join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    methods = list(DEFAULT_METHODS)
    all_rows = []
    confusions = {}
    notes = []
    classes_union = []

    for name, loader in DATASETS.items():
        try:
            labelled = loader()
        except FileNotFoundError:
            print("skip {}: raw dataset not present in .cache/".format(name))
            continue
        labelled = [(s, t) for s, t in labelled if t]
        n, detail = sentinel_report([(s, None, None) for s, _ in labelled])
        notes.append("{}: {} labelled samples; {} contain sub-1e-3 ppm sentinel values {}".format(
            name, len(labelled), n, detail))
        rows, conf, _report, classes = evaluate(name, labelled, methods, subset="all")
        all_rows.extend(rows)
        confusions[name] = conf
        for c in classes:
            if c not in classes_union:
                classes_union.append(c)
        print("evaluated {}: {} samples".format(name, len(labelled)))

        # Second pass excluding the Normal class. Duval Triangle has no "normal"
        # zone, so on a dataset containing healthy units its 100% decision rate
        # becomes a liability rather than a strength. Quantifying that is the
        # point of this pass.
        faults_only = [(s, t) for s, t in labelled if t != "Normal"]
        if len(faults_only) < len(labelled):
            rows2, conf2, _, classes2 = evaluate(name, faults_only, methods, subset="faults_only")
            all_rows.extend(rows2)
            confusions[name + "/faults"] = conf2
            notes.append("{}: {} of {} samples are labelled Normal".format(
                name, len(labelled) - len(faults_only), len(labelled)))

    write_csv(os.path.join(OUT, "summary.csv"), all_rows)
    with open(os.path.join(OUT, "REPORT.md"), "w", encoding="utf-8") as fh:
        fh.write(write_report(all_rows, confusions, sorted(classes_union), notes))

    print("")
    print("{:<13} {:<12} {:<17} {:>8} {:>9} {:>9} {:>7}".format(
        "dataset", "subset", "method", "decided%", "acc_dec%", "acc_all%", "F1"))
    for r in all_rows:
        print("{:<13} {:<12} {:<17} {:>7.1f}% {:>8.1f}% {:>8.1f}% {:>7.3f}".format(
            r["dataset"], r["subset"], r["method"], r["decision_rate_pct"],
            r["acc_of_decided_pct"], r["acc_of_all_pct"], r["macro_f1"]))
    print("\nwrote {}".format(os.path.join(OUT, "REPORT.md")))


if __name__ == "__main__":
    main()
